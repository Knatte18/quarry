// csharp.go implements the C# Strategy: type, method, constructor, property, field, event, indexer and operator extraction, and the C# header, generated-file and test-file rules.
// It registers itself under the canonical language name "csharp" from this file's own init.

package engine

import (
	"strings"

	ts "github.com/tree-sitter/go-tree-sitter"

	"github.com/Knatte18/quarry/glyph"
)

// csharpGeneratedMarker is the text a C# file's leading comment carries when a tool generated the file.
const csharpGeneratedMarker = "<auto-generated"

// csharpStrategy implements Strategy for C# source parsed by the linked tree-sitter-c-sharp grammar.
type csharpStrategy struct{}

func init() {
	Register(csharpStrategy{})
}

// Language implements Strategy by returning "csharp".
func (csharpStrategy) Language() string {
	return "csharp"
}

// csharpWalker accumulates the symbols and dropped ids of one Symbols call.
type csharpWalker struct {
	src     []byte
	symbols []Symbol
	dropped []DroppedSymbol
}

// csharpDecl is everything needed to mint one Symbol.
type csharpDecl struct {
	kind Kind
	// unit is the namespace, "" for the global namespace.
	unit   string
	owner  []string
	name   string
	params []string
	// node gives the declaration's span and signature start.
	node *ts.Node
	// body is the body-bearing child, nil when the declaration has none.
	body *ts.Node
	// docNode is the node whose preceding comments document the symbol, nil when none can.
	docNode *ts.Node
	// head asks for the type head span.
	head    bool
	partial bool
}

// Symbols implements Strategy.
// It walks the compilation unit, every namespace and every type body, descending into preprocessor branches, and mints one Symbol per glyphed declaration.
// It never enters a method, accessor, local-function or lambda body, and never a top-level statement.
// The unit argument is ignored: each symbol's unit is the namespace it is declared in, or "global".
// An id that fails glyph.Parse is left out of the symbol slice and reported in the dropped list.
func (csharpStrategy) Symbols(unit string, root *ts.Node, src []byte) ([]Symbol, []DroppedSymbol) {
	w := &csharpWalker{src: src, symbols: make([]Symbol, 0)}
	w.walkScope(root, "", nil)
	return w.symbols, w.dropped
}

// walkScope visits the declarations that are direct children of parent, a compilation unit, a namespace body, a type body or a preprocessor branch.
// It returns the namespace in force after parent, which a file-scoped namespace declaration changes for the siblings that follow it.
func (w *csharpWalker) walkScope(parent *ts.Node, namespace string, owners []string) string {
	for i := uint(0); i < parent.ChildCount(); i++ {
		child := parent.Child(i)
		switch child.Kind() {
		case "file_scoped_namespace_declaration":
			namespace = joinCSharpNamespace(namespace, csharpNamespaceName(child.ChildByFieldName("name"), w.src))
		case "namespace_declaration":
			if body := child.ChildByFieldName("body"); body != nil {
				inner := joinCSharpNamespace(namespace, csharpNamespaceName(child.ChildByFieldName("name"), w.src))
				w.walkScope(body, inner, nil)
			}
		case "preproc_if", "preproc_elif", "preproc_else":
			namespace = w.walkScope(child, namespace, owners)
		case "class_declaration", "struct_declaration", "interface_declaration",
			"record_declaration", "record_struct_declaration", "enum_declaration", "delegate_declaration":
			w.walkType(child, namespace, owners)
		default:
			if len(owners) > 0 {
				w.walkMember(child, namespace, owners)
			}
		}
	}
	return namespace
}

// walkType mints the symbol of a type declaration and the symbols of its members.
func (w *csharpWalker) walkType(decl *ts.Node, namespace string, owners []string) {
	typeParameters := decl.ChildByFieldName("type_parameters")
	if typeParameters == nil {
		typeParameters = csharpChildOfKind(decl, "type_parameter_list")
	}
	name := w.csharpIdentifier(decl.ChildByFieldName("name")) + csharpArity(typeParameters)
	body := decl.ChildByFieldName("body")
	w.mint(csharpDecl{
		kind: KindType, unit: namespace, owner: owners, name: name,
		node: decl, body: body, docNode: decl, head: true, partial: csharpHasModifier(decl, "partial", w.src),
	})

	chain := append(append([]string(nil), owners...), name)
	primary := csharpChildOfKind(decl, "parameter_list")
	switch decl.Kind() {
	case "record_declaration", "record_struct_declaration":
		if primary != nil {
			w.mintPositionalProperties(primary, body, namespace, chain)
		}
	case "class_declaration", "struct_declaration":
		if primary != nil {
			w.mint(csharpDecl{
				kind: KindConstructor, unit: namespace, owner: chain,
				name:   w.csharpIdentifier(decl.ChildByFieldName("name")),
				params: w.csharpParams(primary), node: primary,
			})
		}
	}

	if body == nil {
		return
	}
	switch body.Kind() {
	case "declaration_list":
		w.walkScope(body, namespace, chain)
	case "enum_member_declaration_list":
		for i := uint(0); i < body.ChildCount(); i++ {
			member := body.Child(i)
			if member.Kind() != "enum_member_declaration" {
				continue
			}
			w.mint(csharpDecl{
				kind: KindConst, unit: namespace, owner: chain,
				name: w.csharpIdentifier(member.ChildByFieldName("name")),
				node: member, docNode: member,
			})
		}
	}
}

// mintPositionalProperties mints one property per positional parameter of a record whose own body declares no member of the same name.
func (w *csharpWalker) mintPositionalProperties(list, body *ts.Node, namespace string, chain []string) {
	declared := w.csharpDeclaredNames(body)
	for i := uint(0); i < list.ChildCount(); i++ {
		param := list.Child(i)
		if param.Kind() != "parameter" {
			continue
		}
		name := w.csharpIdentifier(param.ChildByFieldName("name"))
		if _, taken := declared[name]; taken {
			continue
		}
		w.mint(csharpDecl{kind: KindProperty, unit: namespace, owner: chain, name: name, node: param})
	}
}

// csharpDeclaredNames returns the names of the members declared directly in body, preprocessor branches included.
func (w *csharpWalker) csharpDeclaredNames(body *ts.Node) map[string]struct{} {
	names := make(map[string]struct{})
	if body == nil {
		return names
	}
	var collect func(parent *ts.Node)
	collect = func(parent *ts.Node) {
		for i := uint(0); i < parent.ChildCount(); i++ {
			child := parent.Child(i)
			switch child.Kind() {
			case "preproc_if", "preproc_elif", "preproc_else":
				collect(child)
			case "field_declaration", "event_field_declaration":
				for _, declarator := range csharpDeclarators(child) {
					names[w.csharpIdentifier(declarator.ChildByFieldName("name"))] = struct{}{}
				}
			default:
				if name := child.ChildByFieldName("name"); name != nil {
					names[w.csharpIdentifier(name)] = struct{}{}
				}
			}
		}
	}
	collect(body)
	return names
}

// walkMember mints the symbols of one member declaration of a type.
func (w *csharpWalker) walkMember(decl *ts.Node, namespace string, owners []string) {
	switch decl.Kind() {
	case "method_declaration":
		owner, name := w.csharpQualifiedMember(decl, owners)
		name += csharpArity(decl.ChildByFieldName("type_parameters"))
		w.mint(csharpDecl{
			kind: KindMethod, unit: namespace, owner: owner, name: name,
			params: w.csharpParams(decl.ChildByFieldName("parameters")),
			node:   decl, body: decl.ChildByFieldName("body"), docNode: decl,
			partial: csharpHasModifier(decl, "partial", w.src),
		})
	case "destructor_declaration":
		w.mint(csharpDecl{
			kind: KindMethod, unit: namespace, owner: owners,
			name:   "~" + w.csharpIdentifier(decl.ChildByFieldName("name")),
			params: w.csharpParams(decl.ChildByFieldName("parameters")),
			node:   decl, body: decl.ChildByFieldName("body"), docNode: decl,
		})
	case "constructor_declaration":
		name := w.csharpIdentifier(decl.ChildByFieldName("name"))
		// A constructor is named like its type; the grammar reads a C# 14 extension block as a constructor named "extension".
		if enclosing, _, _ := strings.Cut(owners[len(owners)-1], "<"); name != enclosing {
			return
		}
		if csharpHasModifier(decl, "static", w.src) {
			name = "static " + name
		}
		w.mint(csharpDecl{
			kind: KindConstructor, unit: namespace, owner: owners, name: name,
			params: w.csharpParams(decl.ChildByFieldName("parameters")),
			node:   decl, body: decl.ChildByFieldName("body"), docNode: decl,
		})
	case "operator_declaration":
		name := "operator "
		if csharpHasToken(decl, "checked") {
			name += "checked "
		}
		name += NodeText(decl.ChildByFieldName("operator"), w.src)
		w.mint(csharpDecl{
			kind: KindOperator, unit: namespace, owner: owners, name: name,
			params: w.csharpParams(decl.ChildByFieldName("parameters")),
			node:   decl, body: decl.ChildByFieldName("body"), docNode: decl,
		})
	case "conversion_operator_declaration":
		w.mint(csharpDecl{
			kind: KindOperator, unit: namespace, owner: owners, name: w.csharpConversionName(decl),
			params: w.csharpParams(decl.ChildByFieldName("parameters")),
			node:   decl, body: decl.ChildByFieldName("body"), docNode: decl,
		})
	case "indexer_declaration":
		owner := w.csharpExplicitOwner(decl, owners)
		w.mint(csharpDecl{
			kind: KindIndexer, unit: namespace, owner: owner, name: "this",
			params: w.csharpParams(decl.ChildByFieldName("parameters")),
			node:   decl, body: csharpPropertyBody(decl), docNode: decl,
		})
	case "property_declaration":
		owner, name := w.csharpQualifiedMember(decl, owners)
		w.mint(csharpDecl{
			kind: KindProperty, unit: namespace, owner: owner, name: name,
			node: decl, body: csharpPropertyBody(decl), docNode: decl,
		})
	case "event_declaration":
		owner, name := w.csharpQualifiedMember(decl, owners)
		w.mint(csharpDecl{
			kind: KindEvent, unit: namespace, owner: owner, name: name,
			node: decl, body: decl.ChildByFieldName("accessors"), docNode: decl,
		})
	case "event_field_declaration":
		for _, declarator := range csharpDeclarators(decl) {
			w.mint(csharpDecl{
				kind: KindEvent, unit: namespace, owner: owners,
				name: w.csharpIdentifier(declarator.ChildByFieldName("name")),
				node: decl, docNode: decl,
			})
		}
	case "field_declaration":
		kind := KindField
		if csharpHasModifier(decl, "const", w.src) {
			kind = KindConst
		}
		for _, declarator := range csharpDeclarators(decl) {
			w.mint(csharpDecl{
				kind: kind, unit: namespace, owner: owners,
				name: w.csharpIdentifier(declarator.ChildByFieldName("name")),
				node: decl, docNode: decl,
			})
		}
	}
}

// mint builds the Symbol for d, or records it as dropped when its id does not parse.
func (w *csharpWalker) mint(d csharpDecl) {
	unit := d.unit
	if unit == "" {
		unit = "global"
	}
	g := glyph.Glyph{
		Lang: glyph.CSharp, Unit: unit, Owner: append([]string(nil), d.owner...),
		Name: d.name, Params: d.params,
	}
	if len(g.Owner) == 0 {
		g.Owner = nil
	}
	id := g.String()
	declStart, bodyStart, declEnd := goDeclOffsets(d.node, d.body)
	if _, err := glyph.Parse(glyph.CSharp, id); err != nil {
		w.dropped = append(w.dropped, DroppedSymbol{ID: id, Err: err, DeclStart: declStart, DeclEnd: declEnd})
		return
	}

	start, end := Line(d.node)
	doc := ""
	if d.docNode != nil {
		if first, raw := CommentBlockAbove(d.docNode, w.src); first != nil {
			start, _ = Line(first)
			doc = csharpStripComment(raw)
		}
	}
	sym := Symbol{
		Glyph:     g,
		ID:        id,
		Kind:      d.kind,
		Signature: SignatureCut(d.node, d.body, w.src),
		Doc:       doc,
		Start:     start,
		SigEnd:    SigEnd(d.node, d.body),
		End:       end,
		DeclStart: declStart,
		BodyStart: bodyStart,
		DeclEnd:   declEnd,
		Partial:   d.partial,
	}
	if d.head {
		sym.HeadStart = start
		sym.HeadEnd = csharpHeadEnd(d.node, d.body)
	}
	w.symbols = append(w.symbols, sym)
}

// csharpHeadEnd returns the last line of a type's head: the line the declaration reaches through its base list and constraints, before its body.
// A declaration with no body ends its head with itself.
func csharpHeadEnd(decl, body *ts.Node) int {
	if body == nil {
		_, end := Line(decl)
		return end
	}
	prev := body.PrevSibling()
	for prev != nil && prev.Kind() == "comment" {
		prev = prev.PrevSibling()
	}
	if prev == nil {
		_, end := Line(decl)
		return end
	}
	_, end := Line(prev)
	return end
}

// csharpPropertyBody returns the accessor list of a property or indexer, or its arrow expression when it has no accessors, or nil.
func csharpPropertyBody(decl *ts.Node) *ts.Node {
	if accessors := decl.ChildByFieldName("accessors"); accessors != nil {
		return accessors
	}
	if value := decl.ChildByFieldName("value"); value != nil && value.Kind() == "arrow_expression_clause" {
		return value
	}
	return nil
}

// csharpQualifiedMember returns the owner chain and the name of a member that may be an explicit interface implementation.
// The interface qualifier, canonicalised, is appended to owners as its dotted components.
func (w *csharpWalker) csharpQualifiedMember(decl *ts.Node, owners []string) (owner []string, name string) {
	return w.csharpExplicitOwner(decl, owners), w.csharpIdentifier(decl.ChildByFieldName("name"))
}

// csharpExplicitOwner returns owners extended by the dotted components of decl's explicit interface specifier, if it has one.
func (w *csharpWalker) csharpExplicitOwner(decl *ts.Node, owners []string) []string {
	specifier := csharpChildOfKind(decl, "explicit_interface_specifier")
	if specifier == nil || specifier.NamedChildCount() == 0 {
		return owners
	}
	qualifier := glyph.CanonicalCSharpType(NodeText(specifier.NamedChild(0), w.src))
	return append(append([]string(nil), owners...), csharpSplitDots(qualifier)...)
}

// csharpConversionName returns the member name of a conversion operator: its keyword, "operator", an optional "checked" and the canonical target type.
func (w *csharpWalker) csharpConversionName(decl *ts.Node) string {
	name := "implicit operator "
	if csharpHasToken(decl, "explicit") {
		name = "explicit operator "
	}
	if csharpHasToken(decl, "checked") {
		name += "checked "
	}
	return name + glyph.CanonicalCSharpType(NodeText(decl.ChildByFieldName("type"), w.src))
}

// csharpParams returns the canonical parameter spellings of a parameter list or bracketed parameter list, as a non-nil slice.
// A flattened params entry, which the grammar leaves as bare tokens among the list's children, forms one entry between its commas.
func (w *csharpWalker) csharpParams(list *ts.Node) []string {
	params := []string{}
	if list == nil {
		return params
	}
	var words []string
	flush := func() {
		if len(words) > 0 {
			params = append(params, glyph.CanonicalCSharpType(strings.Join(words, " ")))
			words = nil
		}
	}
	for i := uint(0); i < list.ChildCount(); i++ {
		child := list.Child(i)
		switch {
		case child.Kind() == ",":
			flush()
		case child.Kind() == "parameter":
			flush()
			words = w.parameterWords(child)
			flush()
		case list.FieldNameForChild(uint32(i)) == "type":
			words = append(words, NodeText(child, w.src))
		case !child.IsNamed() && csharpParamModifiers[child.Kind()]:
			words = append(words, child.Kind())
		}
	}
	flush()
	return params
}

// csharpParamModifiers is the set of words a parameter spelling may carry before its type.
var csharpParamModifiers = map[string]bool{
	"ref": true, "out": true, "in": true, "params": true, "this": true, "scoped": true, "readonly": true,
}

// parameterWords returns the modifiers and the type text of one parameter node, in source order.
func (w *csharpWalker) parameterWords(param *ts.Node) []string {
	var words []string
	for i := uint(0); i < param.ChildCount(); i++ {
		child := param.Child(i)
		switch {
		case child.Kind() == "modifier":
			words = append(words, NodeText(child, w.src))
		case param.FieldNameForChild(uint32(i)) == "type":
			words = append(words, NodeText(child, w.src))
		}
	}
	return words
}

// csharpIdentifier returns the identifier text of n with a needless "@" removed.
// A "@" stays only in front of a reserved keyword, which is the same rule the glyph alphabet enforces.
func (w *csharpWalker) csharpIdentifier(n *ts.Node) string {
	if n == nil {
		return ""
	}
	return csharpBareIdentifier(NodeText(n, w.src))
}

// csharpBareIdentifier removes the leading "@" of text unless the glyph alphabet accepts it.
func csharpBareIdentifier(text string) string {
	if !strings.HasPrefix(text, "@") {
		return text
	}
	if _, err := glyph.Parse(glyph.CSharp, "global#"+text); err != nil {
		return text[1:]
	}
	return text
}

// csharpNamespaceName returns a namespace name node's text without whitespace and without needless "@".
func csharpNamespaceName(n *ts.Node, src []byte) string {
	if n == nil {
		return ""
	}
	segments := strings.Split(strings.Join(strings.Fields(NodeText(n, src)), ""), ".")
	for i, segment := range segments {
		segments[i] = csharpBareIdentifier(segment)
	}
	return strings.Join(segments, ".")
}

// joinCSharpNamespace nests inner inside outer, where "" is the global namespace.
func joinCSharpNamespace(outer, inner string) string {
	if outer == "" {
		return inner
	}
	return outer + "." + inner
}

// csharpArity returns the generic arity suffix a type parameter list gives its owner's name: "" without one, "<>" for one parameter, "<,>" for two.
func csharpArity(list *ts.Node) string {
	if list == nil {
		return ""
	}
	count := 0
	for i := uint(0); i < list.NamedChildCount(); i++ {
		if list.NamedChild(i).Kind() == "type_parameter" {
			count++
		}
	}
	if count == 0 {
		return ""
	}
	return "<" + strings.Repeat(",", count-1) + ">"
}

// csharpChildOfKind returns the first direct child of n of the given kind, or nil.
func csharpChildOfKind(n *ts.Node, kind string) *ts.Node {
	for i := uint(0); i < n.ChildCount(); i++ {
		if child := n.Child(i); child.Kind() == kind {
			return child
		}
	}
	return nil
}

// csharpHasModifier reports whether decl carries the modifier word.
func csharpHasModifier(decl *ts.Node, word string, src []byte) bool {
	for i := uint(0); i < decl.ChildCount(); i++ {
		if child := decl.Child(i); child.Kind() == "modifier" && NodeText(child, src) == word {
			return true
		}
	}
	return false
}

// csharpHasToken reports whether decl has a direct anonymous child token of the given text.
func csharpHasToken(decl *ts.Node, token string) bool {
	for i := uint(0); i < decl.ChildCount(); i++ {
		if child := decl.Child(i); !child.IsNamed() && child.Kind() == token {
			return true
		}
	}
	return false
}

// csharpDeclarators returns the variable_declarator nodes of a field or event field declaration, one per declared name.
func csharpDeclarators(decl *ts.Node) []*ts.Node {
	declaration := csharpChildOfKind(decl, "variable_declaration")
	if declaration == nil {
		return nil
	}
	var declarators []*ts.Node
	for i := uint(0); i < declaration.ChildCount(); i++ {
		if child := declaration.Child(i); child.Kind() == "variable_declarator" {
			declarators = append(declarators, child)
		}
	}
	return declarators
}

// csharpSplitDots splits a canonical type spelling into its dotted components, leaving dots inside "<>" alone.
func csharpSplitDots(spelling string) []string {
	var parts []string
	depth, start := 0, 0
	for i := 0; i < len(spelling); i++ {
		switch spelling[i] {
		case '<', '(', '[':
			depth++
		case '>', ')', ']':
			depth--
		case '.':
			if depth == 0 {
				parts = append(parts, spelling[start:i])
				start = i + 1
			}
		}
	}
	return append(parts, spelling[start:])
}

// csharpStripComment removes the delimiters of a C# comment block.
// A "///" line loses all three slashes and a "//" line its two, with XML kept verbatim; a "/* */" block loses its delimiters.
func csharpStripComment(raw string) string {
	if strings.HasPrefix(strings.TrimLeft(raw, " \t\r\n"), "/*") {
		return StripComment(raw, "//")
	}
	lines := strings.Split(raw, "\n")
	for i, line := range lines {
		trimmed := strings.TrimSpace(line)
		if rest, ok := strings.CutPrefix(trimmed, "///"); ok {
			trimmed = rest
		} else {
			trimmed = strings.TrimPrefix(trimmed, "//")
		}
		lines[i] = strings.TrimSpace(trimmed)
	}
	return strings.TrimSpace(strings.Join(lines, "\n"))
}

// Header implements Strategy by returning the first leading comment block that does not carry the generated-file marker, delimiter-stripped, or "" when there is none.
func (csharpStrategy) Header(root *ts.Node, src []byte) string {
	for _, block := range LeadingBlocks(root, src) {
		stripped := csharpStripComment(block.Raw)
		if generated, _ := GeneratedByBanner("csharp", stripped); !generated {
			return stripped
		}
	}
	return ""
}

// Package implements Strategy by returning the first namespace the file declares, or "" when it declares none.
func (csharpStrategy) Package(root *ts.Node, src []byte) string {
	var find func(parent *ts.Node) (string, bool)
	find = func(parent *ts.Node) (string, bool) {
		for i := uint(0); i < parent.ChildCount(); i++ {
			child := parent.Child(i)
			switch child.Kind() {
			case "namespace_declaration", "file_scoped_namespace_declaration":
				return csharpNamespaceName(child.ChildByFieldName("name"), src), true
			case "preproc_if", "preproc_elif", "preproc_else":
				if name, ok := find(child); ok {
					return name, true
				}
			}
		}
		return "", false
	}
	name, _ := find(root)
	return name
}

// Namespaces implements namespaceDeclarer by returning every namespace the file declares and every prefix of it, each once.
// `namespace A.B;` and `namespace A { namespace B {} }` both report "A.B" and "A".
func (csharpStrategy) Namespaces(root *ts.Node, src []byte) []string {
	var names []string
	seen := make(map[string]struct{})
	declare := func(namespace string) {
		for namespace != "" {
			if _, dup := seen[namespace]; dup {
				return
			}
			seen[namespace] = struct{}{}
			names = append(names, namespace)
			cut := strings.LastIndex(namespace, ".")
			if cut < 0 {
				return
			}
			namespace = namespace[:cut]
		}
	}

	var walk func(parent *ts.Node, namespace string) string
	walk = func(parent *ts.Node, namespace string) string {
		for i := uint(0); i < parent.ChildCount(); i++ {
			child := parent.Child(i)
			switch child.Kind() {
			case "file_scoped_namespace_declaration":
				if name := csharpNamespaceName(child.ChildByFieldName("name"), src); name != "" {
					namespace = joinCSharpNamespace(namespace, name)
					declare(namespace)
				}
			case "namespace_declaration":
				name := csharpNamespaceName(child.ChildByFieldName("name"), src)
				if name == "" {
					continue
				}
				inner := joinCSharpNamespace(namespace, name)
				declare(inner)
				if body := child.ChildByFieldName("body"); body != nil {
					walk(body, inner)
				}
			case "preproc_if", "preproc_elif", "preproc_else":
				namespace = walk(child, namespace)
			}
		}
		return namespace
	}
	walk(root, "")
	return names
}

// PackageDoc implements Strategy by returning "": a namespace carries no documentation of its own.
func (csharpStrategy) PackageDoc(root *ts.Node, src []byte) string {
	return ""
}

// Generated implements Strategy by delegating to GeneratedByBanner("csharp", ...) on the first leading comment block, delimiter-stripped.
func (csharpStrategy) Generated(root *ts.Node, src []byte) bool {
	blocks := LeadingBlocks(root, src)
	if len(blocks) == 0 {
		return false
	}
	generated, _ := GeneratedByBanner("csharp", csharpStripComment(blocks[0].Raw))
	return generated
}

// TestFile implements Strategy by delegating to TestFileByName("csharp", base), which is always false.
func (csharpStrategy) TestFile(base string) bool {
	isTest, _ := TestFileByName("csharp", base)
	return isTest
}
