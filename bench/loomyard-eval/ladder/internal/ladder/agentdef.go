// agentdef.go generates the Claude Code agent definitions the session-provisioning batch writes into a
// scratch directory's .claude/agents/ tree: the per-config run agent carrying that config's tool
// allowlist, the single shared scorer agent, and the two permission-probe agents. It also carries the
// inverse reader that recovers a written definition's granted-tool list, so the generator and the
// extractor can never drift apart.

package ladder

import (
	"bytes"
	"fmt"
	"os"
	"strings"

	"gopkg.in/yaml.v3"
)

// baseRunTools are the four tools every generated run, probe, and blinded-control definition grants
// independent of any quarry exposure -- read, search, and shell access, identical across the whole
// matrix.
var baseRunTools = []string{"Read", "Grep", "Glob", "Bash"}

// probeDeniedTool is the one canonical tool the two probe definitions/settings exercise -- an arbitrary
// daemon-backed choice, since what the probe establishes is whether each enforcement layer blocks at
// all, not whether this particular tool is safe. Mirrors the Python port's own _PROBE_DENIED_TOOL.
const probeDeniedTool = "impact"

// ModelAlias maps a pinned model id to the Claude Code agent-definition model alias it must be launched
// with -- the opus id to "opus" and the sonnet id to "sonnet" -- erroring on any other id.
//
// This mapping is verified empirically by the model pinning gate (GateModelPinned), which compares a
// run's transcript-reported model string against the pinned id, only on the first real matrix run --
// nothing in this package checks in advance that Claude Code actually resolves the "opus"/"sonnet"
// alias back to the exact pinned id this mapping assumes.
func ModelAlias(modelID string) (string, error) {
	switch modelID {
	case "claude-opus-5":
		return "opus", nil
	case "claude-sonnet-5":
		return "sonnet", nil
	default:
		return "", fmt.Errorf("ladder: model alias: no agent-definition alias is mapped for model id %q", modelID)
	}
}

// agentFrontmatter is the parsed shape of a generated agent definition's YAML frontmatter. Model and
// Effort are omitted from the rendered document when empty, which is the shape ProbeAgentDefinition's
// definitions use -- a probe pins neither, launching under whatever --model flag the dispatching command
// supplies.
type agentFrontmatter struct {
	Name        string   `yaml:"name"`
	Description string   `yaml:"description"`
	Model       string   `yaml:"model,omitempty"`
	Effort      string   `yaml:"effort,omitempty"`
	Tools       []string `yaml:"tools"`
}

// renderAgentDefinition serialises fm and body as the "---\n<yaml>---\n\n<body>\n" document Claude Code
// reads an agent definition from. fm.Tools is always rendered explicitly, even when empty, since an
// empty allowlist is itself a meaningful value (see ScorerAgentDefinition) that must round-trip back
// through GrantedToolsFromDefinition as an empty slice, not as an absent key.
func renderAgentDefinition(fm agentFrontmatter, body string) (string, error) {
	if fm.Tools == nil {
		fm.Tools = []string{}
	}
	var buf bytes.Buffer
	encoder := yaml.NewEncoder(&buf)
	encoder.SetIndent(2)
	if err := encoder.Encode(fm); err != nil {
		return "", fmt.Errorf("ladder: render agent definition: marshal frontmatter: %w", err)
	}
	if err := encoder.Close(); err != nil {
		return "", fmt.Errorf("ladder: render agent definition: close frontmatter encoder: %w", err)
	}
	return "---\n" + buf.String() + "---\n\n" + strings.TrimRight(body, "\n") + "\n", nil
}

// runAgentPromptBody is the system-prompt body every generated run agent definition carries, identical
// across every config -- blinded or rung alike -- so no config's body can itself leak which case it is
// by differing in wording. It never names quarry: the config's own tool allowlist, rendered into the
// frontmatter's tools: key, is what actually varies per config.
const runAgentPromptBody = `You are the ladder benchmark's run agent for this session. Complete the task
described in the prompt you are given, using only the tools granted to you above. When you are done,
follow the prompt's own closing instructions for how to report your answer.`

// RunAgentDefinition generates the Claude Code agent definition for one main-matrix run of config under
// runModel: YAML frontmatter carrying a name, a description, the resolved model alias, l's configured
// run effort, and a tools: allowlist of Read/Grep/Glob/Bash plus config's allowed quarry tools under
// their prefixed mcp__quarry__* client-side names.
//
// The allowlist never contains "Task": a run agent generated by this function cannot spawn its own
// subagents, because nothing in its own tool list lets it try. This is the only layer that denies Task
// -- the settings document (settings.go's SettingsDocumentFor) deliberately does not also deny it at the
// session level, since that would leave the operator's own live session unable to dispatch the run agent
// in the first place.
//
// For a config whose Allowed is empty, the definition's name, description, and body are the fixed
// blinding-safe constants this function always uses -- they never name quarry or any prefixed tool,
// because the definition sits in the blinded agent's own cwd.
func RunAgentDefinition(l *Ladder, c LadderConfig, runModel string) (name, body string, err error) {
	alias, err := ModelAlias(runModel)
	if err != nil {
		return "", "", err
	}

	tools := append([]string{}, baseRunTools...)
	for _, tool := range l.QuarryTools {
		if stringSliceContains(c.Allowed, tool) {
			tools = append(tools, MCPName(tool))
		}
	}

	name = c.ID
	doc, err := renderAgentDefinition(agentFrontmatter{
		Name:        name,
		Description: fmt.Sprintf("Ladder capability-bench run agent for config %s.", c.ID),
		Model:       alias,
		Effort:      l.RunEffort,
		Tools:       tools,
	}, runAgentPromptBody)
	if err != nil {
		return "", "", err
	}
	return name, doc, nil
}

// scorerAgentName is the fixed name every ScorerAgentDefinition uses, matching the fixed
// .claude/agents/scorer.md filename PrepareScoringSession writes it under.
const scorerAgentName = "scorer"

// scorerPromptBody is the scorer agent's system-prompt body. It grants no tools, so it reads only the
// scoring instructions and reference material given directly in its prompt -- it never reaches out to
// re-derive anything from disk.
const scorerPromptBody = `You are the ladder benchmark's scoring agent, shared across every run in this
matrix. Score the run given to you in your prompt strictly against the rubric it provides, using only
the material given directly in that prompt.`

// ScorerAgentDefinition generates the single scorer agent definition, identical for every config since
// only l's scorer model and effort parameterise it: pinned to the opus alias at l's configured scorer
// effort, and granting no tools at all.
//
// A zero-tool scorer is what makes one shared scoring session safe across the whole matrix: it cannot
// read the session transcript accumulating the other runs' answer keys, or anything else on disk --
// every fact it scores against must already be in the prompt it is dispatched with.
func ScorerAgentDefinition(l *Ladder) (name, body string, err error) {
	alias, err := ModelAlias(l.Scorer.Model)
	if err != nil {
		return "", "", err
	}

	doc, err := renderAgentDefinition(agentFrontmatter{
		Name:        scorerAgentName,
		Description: "Ladder capability-bench scoring agent, shared across the whole matrix.",
		Model:       alias,
		Effort:      l.Scorer.Effort,
		Tools:       []string{},
	}, scorerPromptBody)
	if err != nil {
		return "", "", err
	}
	return scorerAgentName, doc, nil
}

// Probe kind names ProbeAgentDefinition and PrepareProbeSession accept -- see their doc comments for
// what each kind establishes.
const (
	// ProbeKindAllowlist names the probe whose agent definition withholds the probed tool from its own
	// tools: allowlist while its settings do not deny it -- establishing that the allowlist layer alone
	// blocks the call.
	ProbeKindAllowlist = "allowlist"
	// ProbeKindDenylist names the probe whose agent definition grants the probed tool while its settings
	// deny it -- establishing that the settings deny-list layer alone blocks the call.
	ProbeKindDenylist = "denylist"
)

// probePromptBody is the system-prompt body both probe agent definitions share: an instruction to call
// the probed tool and report verbatim what happened, so the probe result records the enforcement layer's
// actual behaviour rather than the agent's own paraphrase.
const probePromptBody = `You are a permission probe agent. Call the probed tool named in your prompt
once, with any plausible arguments for it, and report exactly what happened when you called it --
whether it succeeded, was denied, or errored, quoting the tool result you received verbatim.`

// ProbeAgentDefinition generates one of the two permission-probe agent definitions: the allowlist probe
// (kind == ProbeKindAllowlist) grants the four base tools but withholds the prefixed probeDeniedTool
// name from its own allowlist, while the deny-list probe (kind == ProbeKindDenylist) grants it. Both ask
// the agent to call that tool and report verbatim what happened.
//
// Neither probe definition pins a model or effort -- both launch under whatever --model flag the
// dispatching command supplies, since the probe is establishing an enforcement-layer fact independent of
// which model runs it.
//
// Returns an error naming kind when it is neither ProbeKindAllowlist nor ProbeKindDenylist.
func ProbeAgentDefinition(l *Ladder, kind string) (name, body string, err error) {
	_ = l // accepted for signature symmetry with RunAgentDefinition/ScorerAgentDefinition; unused here.

	var tools []string
	switch kind {
	case ProbeKindAllowlist:
		name = "probe-allowlist"
		tools = append([]string{}, baseRunTools...)
	case ProbeKindDenylist:
		name = "probe-denylist"
		tools = append(append([]string{}, baseRunTools...), MCPName(probeDeniedTool))
	default:
		return "", "", fmt.Errorf("ladder: probe agent definition: unknown probe kind %q", kind)
	}

	doc, err := renderAgentDefinition(agentFrontmatter{
		Name:        name,
		Description: "Ladder capability-bench permission probe agent.",
		Tools:       tools,
	}, probePromptBody)
	if err != nil {
		return "", "", err
	}
	return name, doc, nil
}

// extractFrontmatter returns the YAML text between a leading "---\n" delimiter and the following "\n---"
// delimiter in doc, and whether both delimiters were found.
func extractFrontmatter(doc string) (yamlText string, ok bool) {
	const open = "---\n"
	if !strings.HasPrefix(doc, open) {
		return "", false
	}
	rest := doc[len(open):]
	end := strings.Index(rest, "\n---")
	if end == -1 {
		return "", false
	}
	return rest[:end], true
}

// GrantedToolsFromDefinition parses a written agent definition's tools: frontmatter back into the
// allowlist it grants. It is the sole producer of the granted-tool list the usage extractor records, and
// it lives beside RunAgentDefinition/ScorerAgentDefinition/ProbeAgentDefinition so the two shapes cannot
// drift apart.
//
// It errors on a missing file, on a document with no "---" delimited frontmatter, on frontmatter that
// fails to parse as YAML, and on frontmatter with no tools: key at all -- never returning an empty slice
// for any of these, because an empty allowlist is a meaningful value a blinded config or the scorer
// legitimately produces (see ScorerAgentDefinition), and silently conflating it with a parse failure
// would record a false granted-tool set.
func GrantedToolsFromDefinition(path string) ([]string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("ladder: granted tools from definition: read %s: %w", path, err)
	}

	frontmatterYAML, ok := extractFrontmatter(string(data))
	if !ok {
		return nil, fmt.Errorf("ladder: granted tools from definition: %s has no --- delimited frontmatter", path)
	}

	var parsed struct {
		Tools *[]string `yaml:"tools"`
	}
	if err := yaml.Unmarshal([]byte(frontmatterYAML), &parsed); err != nil {
		return nil, fmt.Errorf("ladder: granted tools from definition: parse frontmatter in %s: %w", path, err)
	}
	if parsed.Tools == nil {
		return nil, fmt.Errorf("ladder: granted tools from definition: %s frontmatter has no tools key", path)
	}
	return *parsed.Tools, nil
}
